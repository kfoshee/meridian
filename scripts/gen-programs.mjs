// Generates app/landing/programs.ts from the console's revenue-stream registry, so the public page and the
// product cannot disagree. Run: node scripts/gen-programs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const here = dirname(fileURLToPath(import.meta.url));
const REG = join(here, "../../packages/meridian-contracts/fixtures/revenue-stream/registry.json");
const OUT = join(here, "../app/landing/programs.ts");
const reg = JSON.parse(readFileSync(REG, "utf8"));
const by = Object.fromEntries(reg.streams.map(s => [s.id, s]));
const num = v => (v == null || v === "None" ? null : Number(v));
const stream = (id) => { const s = by[id]; if (!s) throw new Error(`registry has no stream ${id}`); return s; };
const rate = (s) => [num(s.rate_low), num(s.rate_high)];
const cite = (s) => ({ file: s.citation?.file ?? "", url: s.citation?.url ?? "", retrieved: s.citation?.retrieved ?? "" });

// ERCOT reserves: every ancillary and ERS stream, as a range of $ per MW-hour committed. Never annualised here.
const anc = reg.streams.filter(s => s.market === "ercot" && s.kind === "ancillary");
const ancLo = Math.min(...anc.map(s => num(s.rate_low))), ancHi = Math.max(...anc.map(s => num(s.rate_high)));
const ancYears = [...new Set(anc.map(s => s.year))].sort().join("–");
const fourcp = { Oncor: "ercot_4cp_oncor", CenterPoint: "ercot_4cp_centerpoint", "AEP Texas": "ercot_4cp_aep_texas_north", TNMP: "ercot_4cp_tnmp" };
const tdus = Object.values(fourcp).map(stream);
const ercotB = { rate: [ancLo, ancHi], unit: "per MW-hour committed", scale: "rate", short: "ERS or reserves", name: `ERS or reserves (ECRS / RRS / NSRS), ${ancYears}`, status: "published_2025, estimate_2026", cite: cite(stream("ercot_ers")) };
const ercotProgram = (name, s) => ({
  a: { rate: rate(s), unit: "per MW a year", scale: "mw", name: s.name, status: s.status, year: String(s.year), cite: cite(s) },
  b: ercotB, priced: true, model: true,
  note: `${name} 4CP, PUCT rate report ${s.year} · ERS and reserves as cleared, ${ancYears}`,
});
const la = stream("ladwp_capacity_day_ahead"), ls = stream("ladwp_capacity_short_notice"), le = stream("ladwp_event_energy");
const programs = {
  ...Object.fromEntries(Object.entries(fourcp).map(([k, id]) => [k, ercotProgram(k, stream(id))])),
  ERCOT: { ...ercotProgram("Texas utilities", tdus[0]), a: { rate: [Math.min(...tdus.map(s => num(s.rate_low))), Math.max(...tdus.map(s => num(s.rate_high)))], unit: "per MW a year", scale: "mw", name: "4CP avoided transmission charge, TNMP to CenterPoint", status: tdus[0].status, year: String(tdus[0].year), cite: cite(tdus[0]) }, note: `4CP across the four Texas utilities, PUCT rate reports ${tdus[0].year} · ERS and reserves as cleared, ${ancYears}` },
  LADWP: {
    a: { rate: [num(la.rate_low), num(ls.rate_high)], unit: "per kW a month of the season", scale: "kw", name: "LADWP demand response capacity incentive, day-ahead to two-hour notice", status: ls.status, year: String(ls.year), cite: cite(ls) },
    b: { rate: rate(le), unit: "per kWh delivered in events", scale: "rate", short: "event energy", name: le.name, status: le.status, cite: cite(le) },
    priced: true, model: false, note: `LADWP capacity incentive, $${num(la.rate_low)} to $${num(ls.rate_high)} per kW a month, June 15 to October 15, ${ls.year} terms. Event energy is additional.`,
  },
  CAISO: { a: null, b: null, priced: false, model: false, note: "Not priced yet: no program source on file for California outside Los Angeles." },
};
const ts = `// GENERATED by scripts/gen-programs.mjs from packages/meridian-contracts/fixtures/revenue-stream/registry.json
// (registry version ${reg.version}, ${reg.streams.length} streams). Do not edit by hand; edit the registry and regenerate.
// Rules carried over from the registry: streams are never summed, and monthly or hourly rates are never
// multiplied into a season or a year. Each rate keeps the unit and period the program document states.
export type Program = "Oncor" | "CenterPoint" | "AEP Texas" | "TNMP" | "ERCOT" | "LADWP" | "CAISO";
export type Stream = {
  rate: [number, number];                              // low–high as published; equal when a single rate
  unit: string;                                        // the published unit, e.g. "per MW a year"
  scale: "mw" | "kw" | "rate";                         // how a site's flexible MW applies: × MW, × MW × 1000, or not at all (show the rate)
  name: string; short?: string; status: string; year?: string;
  cite: { file: string; url: string; retrieved: string };
};
export type ProgramRates = { a: Stream | null; b: Stream | null; priced: boolean; model: boolean; note: string };
export const PROGRAMS: Record<Program, ProgramRates> = ${JSON.stringify(programs, null, 2)};
// The share of a campus Meridian designs as flexible in the illustrative campus above (40 of 96 MW).
// An illustration, not a facility result: a real site's share comes from its own assessment.
export const FLEX_SHARE = 0.4;
export const money = (v: number) => v >= 1e6 ? \`$\${(v / 1e6).toFixed(1)}M\` : v >= 1e3 ? \`$\${Math.round(v / 1e3)}k\` : v >= 100 ? \`$\${Math.round(v)}\` : \`$\${v.toFixed(2)}\`;
export const range = (lo: number, hi: number) => lo === hi ? money(lo) : \`\${money(lo)} – \${money(hi)}\`;
// A stream applied to a site's flexible MW, in the stream's own period: a value and the words after it.
export const applied = (s: Stream, mw: number): { text: string; after: string } => {
  if (s.scale === "mw") return { text: range(s.rate[0] * mw, s.rate[1] * mw), after: "a year" };
  if (s.scale === "kw") return { text: range(s.rate[0] * mw * 1000, s.rate[1] * mw * 1000), after: "a month of the season" };
  return { text: range(s.rate[0], s.rate[1]), after: s.unit };
};
`;
writeFileSync(OUT, ts);
console.log(`wrote ${OUT} from ${reg.streams.length} streams`);
